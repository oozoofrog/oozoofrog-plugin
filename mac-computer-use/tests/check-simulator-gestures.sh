#!/bin/bash
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
source="$here/../skills/mac-computer-use/scripts/mac-cu-src"
out="$(mktemp -d "${TMPDIR:-/tmp}/mac-cu-gesture-check.XXXXXX")"
trap 'rm -rf "$out"' EXIT
swiftc "$source/SimulatorGestures.swift" "$here/simulator-gestures-selfcheck.swift" -o "$out/timeline"
"$out/timeline"
swiftc -parse-as-library "$source/SimulatorGestureHID.swift" "$here/gesture-hid-selfcheck.swift" -o "$out/hid"
"$out/hid"
swiftc -parse-as-library "$source/SimulatorTouchOverlay.swift" "$here/simulator-touch-overlay-selfcheck.swift" -o "$out/overlay"
"$out/overlay"
swiftc -parse-as-library "$source/SimulatorPreviewLayout.swift" "$here/simulator-preview-layout-selfcheck.swift" -o "$out/layout"
"$out/layout"
swiftc -parse-as-library "$source/SimulatorDisplayState.swift" "$here/simulator-display-state-selfcheck.swift" -o "$out/display-state"
"$out/display-state"
swiftc -parse-as-library "$source/SimulatorKeyboardState.swift" "$here/simulator-keyboard-state-selfcheck.swift" -o "$out/keyboard-state"
"$out/keyboard-state"
chrome=("$source/SimulatorDeviceContainer.swift" "$source/SimulatorLCDContent.swift" "$source/SimulatorDeviceChrome.swift" "$source/SimulatorGesturePad.swift" "$source/SimulatorToolbox.swift" "$source/SimulatorToolbarDocking.swift")
swiftc -parse-as-library "${chrome[@]}" "$here/simulator-toolbox-selfcheck.swift" -o "$out/toolbox"
"$out/toolbox"
swiftc -parse-as-library "${chrome[@]}" "$here/simulator-device-chrome-selfcheck.swift" -o "$out/chrome"
"$out/chrome"
swiftc -parse-as-library "${chrome[@]}" "$here/simulator-toolbar-docking-selfcheck.swift" -o "$out/docking"
"$out/docking"
swiftc -parse-as-library "$source/SimulatorPreviewLayout.swift" "$source/SimulatorWindowPresentation.swift" "$here/simulator-window-presentation-selfcheck.swift" -o "$out/windows"
"$out/windows"
swiftc -parse-as-library "$source/SimulatorWindowOcclusion.swift" "$here/simulator-window-occlusion-selfcheck.swift" -o "$out/occlusion"
"$out/occlusion"
python3 "$here/../docs/development/gesture-probe/check_trace.py" --self-test
node "$here/../docs/development/gesture-probe/playground-selfcheck.mjs"
python3 "$here/setup-icon-selfcheck.py"
